import type { AgentAccessAction } from "@paperclipai/shared";

/**
 * Which access action each REST write route needs when the caller acts as an agent (step 4a,
 * fork/step-4a-mcp-and-permissions.md, section 3). Paths are Express patterns as mounted under
 * `/api`. `"route_checks"` means the route decides access itself (a task's own-or-any rule, its
 * comment rule, or a board-only check), so the policy only asks for `tasks:read`.
 *
 * Every write route in the OpenAPI document must be listed here: `agent-route-policy.test.ts`
 * fails otherwise. A write route that isn't listed (an undocumented one) needs `api:raw`, and so
 * do the routes tagged `api:raw` below: company, instance, connection, secret and plugin
 * configuration. Reads (GET, HEAD, OPTIONS) need `tasks:read` plus the routes' own visibility
 * checks. People (board callers) are never checked here.
 */
export type AgentRoutePolicyAction = AgentAccessAction | readonly AgentAccessAction[] | "route_checks";

export type AgentRoutePolicyEntry = {
  method: "POST" | "PATCH" | "PUT" | "DELETE";
  path: string;
  action: AgentRoutePolicyAction;
};

function tag(action: AgentRoutePolicyAction, routes: readonly string[]): AgentRoutePolicyEntry[] {
  return routes.map((route) => {
    const [method, path] = route.split(" ") as [AgentRoutePolicyEntry["method"], string];
    return { method, path, action };
  });
}

