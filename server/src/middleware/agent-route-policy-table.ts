type CompiledEntry = AgentRoutePolicyEntry & { segments: string[]; literals: number };

function splitPath(path: string) {
  return path.split("/").filter((segment) => segment.length > 0);
}

const COMPILED: CompiledEntry[] = AGENT_ROUTE_POLICY.map((entry) => {
  const segments = splitPath(entry.path);
  return { ...entry, segments, literals: segments.filter((segment) => !segment.startsWith(":")).length };
});

/**
 * The table entry for a request, with its path parameters. When several patterns match, the one
 * with the most literal segments wins (`/issues/:id/read` over `/issues/:id/:anything`).
 */
export function matchAgentRoutePolicy(method: string, path: string):
  { entry: AgentRoutePolicyEntry; params: Record<string, string> } | null {
  const upper = method.toUpperCase();
  const requested = splitPath(path.split("?")[0] ?? "");
  let best: { entry: CompiledEntry; params: Record<string, string> } | null = null;
  for (const entry of COMPILED) {
    if (entry.method !== upper || entry.segments.length !== requested.length) continue;
    const params: Record<string, string> = {};
    let matched = true;
    for (let index = 0; index < entry.segments.length; index += 1) {
      const pattern = entry.segments[index]!;
      const value = requested[index]!;
      if (pattern.startsWith(":")) {
        params[pattern.slice(1)] = safeDecode(value);
      } else if (pattern !== value) {
        matched = false;
        break;
      }
    }
    if (matched && (!best || entry.literals > best.entry.literals)) best = { entry, params };
  }
  return best ? { entry: best.entry, params: best.params } : null;
}

function safeDecode(value: string) {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
}

/**
 * What an agent caller needs for a request: any one of `actions`. `routeChecks` is true when the
 * route decides the rest itself; `tagged` is false for an unlisted write route.
 */
export function agentRouteRequirement(method: string, path: string): {
  actions: readonly AgentAccessAction[];
  write: boolean;
  routeChecks: boolean;
  tagged: boolean;
  params: Record<string, string>;
} {
  const upper = method.toUpperCase();
  if (upper !== "POST" && upper !== "PATCH" && upper !== "PUT" && upper !== "DELETE") {
    return { actions: ["tasks:read"], write: false, routeChecks: true, tagged: true, params: {} };
  }
  const match = matchAgentRoutePolicy(upper, path);
  if (!match) return { actions: ["api:raw"], write: true, routeChecks: false, tagged: false, params: {} };
  const { action } = match.entry;
  if (action === "route_checks") {
    return { actions: ["tasks:read"], write: true, routeChecks: true, tagged: true, params: match.params };
  }
  return {
    actions: typeof action === "string" ? [action] : action,
    write: true,
    routeChecks: false,
    tagged: true,
    params: match.params,
  };
}
